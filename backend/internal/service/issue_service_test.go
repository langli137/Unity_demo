func TestUpdateStatusConflict(t *testing.T) {
	repo := &racingRepo{IssueRepo: mem.New()}
	svc := newService(repo)
	issue := mustCreate(t, svc)

	// 状态机校验通过后、条件更新前，另一人抢先把状态改为 resolved。
	repo.race = func(id string) {
		ms := time.Now().UnixMilli()
		repo.race = nil
		if _, err := repo.UpdateStatusIfCurrent(context.Background(), id,
			model.StatusOpen, model.StatusResolved, ms, &ms); err != nil {
			t.Fatal(err)
		}
	}

	got, err := svc.UpdateStatus(context.Background(), issue.ID, model.StatusResolved)
	// 读到的旧状态是 open，目标 resolved 三态下合法，但条件更新时状态已被改为 resolved → 409。
	if !errors.Is(err, ErrConflict) {
		t.Fatalf("err = %v, want ErrConflict", err)
	}
	if got == nil || got.Status != model.StatusResolved {
		t.Errorf("conflict should return latest issue, got %+v", got)
	}
}

// TestUpdateIssueFields 字段编辑：仅改可编辑字段，status/position/anchor 不受影响（v1.2）。
func TestUpdateIssueFields(t *testing.T) {
	svc := newService(mem.New())
	issue := mustCreate(t, svc)

	got, err := svc.UpdateIssue(context.Background(), issue.ID, UpdateIssueInput{
		Title:        "  入口墙面裂缝（修补后复查）  ",
		Description:  "裂缝宽约 3mm，位于墙体中部",
		Category:     model.CategorySafetyHazard,
		Priority:     model.PriorityLow,
		ReporterName: " 李四 ",
	})
	if err != nil {
		t.Fatalf("UpdateIssue: %v", err)
	}
	if got.Title != "入口墙面裂缝（修补后复查）" {
		t.Errorf("title = %q, want trimmed", got.Title)
	}
	if got.Category != model.CategorySafetyHazard || got.Priority != model.PriorityLow {
		t.Errorf("category/priority = %s/%s", got.Category, got.Priority)
	}
	if got.ReporterName != "李四" {
		t.Errorf("reporterName = %q, want trimmed", got.ReporterName)
	}
	// 不可编辑字段必须保持原值：状态机与 AR 定位不受字段编辑影响。
	if got.Status != model.StatusOpen {
		t.Errorf("status touched by field edit: %s", got.Status)
	}
	if got.Position.X != 0.42 || got.Position.Z != 1.26 || got.Anchor.PlaneID != "plane-1" {
		t.Errorf("position/anchor touched: %+v / %+v", got.Position, got.Anchor)
	}
	// now 为固定时钟，UpdatedAt 不推进；ID/CreatedAt 保持不变即可。
	if got.ID != issue.ID || !got.CreatedAt.Equal(issue.CreatedAt) {
		t.Error("id/createdAt should be immutable on field edit")
	}
}

