// racingRepo 模拟并发冲突：在 GetByID 之后、UpdateStatusIfCurrent 之前状态被他人改掉。
type racingRepo struct {
	*mem.IssueRepo
	race func(id string)
}

func (r *racingRepo) UpdateStatusIfCurrent(ctx context.Context, id string, from, to model.Status, updatedAt int64, resolvedAt *int64) (bool, error) {
	if r.race != nil {
		r.race(id)
	}
	return r.IssueRepo.UpdateStatusIfCurrent(ctx, id, from, to, updatedAt, resolvedAt)
}

func newService(repo repository.IssueRepository) *IssueService {
	svc := NewIssueService(repo)
	svc.now = func() time.Time { return time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC) }
	return svc
}

func mustCreate(t *testing.T, svc *IssueService) *model.Issue {
	t.Helper()
	issue, err := svc.CreateIssue(context.Background(), CreateIssueInput{
		Title:    "墙面破损",
		Category: model.CategoryWallDamage,
		Priority: model.PriorityHigh,
		Position: model.Vector3{X: 0.42, Y: 0.03, Z: 1.26},
		Anchor:   model.Anchor{PlaneID: "plane-1"},
	})
	if err != nil {
		t.Fatalf("CreateIssue: %v", err)
	}
	return issue
}

func TestCreateIssueDefaultsAndValidation(t *testing.T) {
	svc := newService(mem.New())

	issue := mustCreate(t, svc)
	if issue.Status != model.StatusOpen {
		t.Errorf("new issue status = %s, want open", issue.Status)
	}
	if issue.ID == "" {
		t.Error("ID should be generated by server")
	}
	if issue.Position.X != 0.42 || issue.Position.Z != 1.26 {
		t.Errorf("position not stored: %+v", issue.Position)
	}

	// D3：category 缺省 other；planeId 选填，不传也可创建成功。
	relaxed, err := svc.CreateIssue(context.Background(), CreateIssueInput{
		Title: "无扩展信息问题", Priority: model.PriorityMedium,
		Position: model.Vector3{X: 1, Y: 0, Z: 2},
	})
	if err != nil {
		t.Fatalf("create without category/anchor: %v", err)
	}
	if relaxed.Category != model.CategoryOther {
		t.Errorf("category default = %q, want other", relaxed.Category)
	}

	cases := []CreateIssueInput{
		{Title: "  ", Category: model.CategoryOther, Priority: model.PriorityLow},
		{Title: "x", Category: "bad", Priority: model.PriorityLow}, // 非法枚举仍 400
		{Title: "x", Category: model.CategoryOther, Priority: "bad"},
	}
	for i, in := range cases {
		if _, err := svc.CreateIssue(context.Background(), in); !errors.Is(err, ErrValidation) {
			t.Errorf("case %d: err = %v, want ErrValidation", i, err)
		}
	}
}

// TestStatusTransitions 三态任意互转（含回退、跨态、自转）一律合法（v1.1 Q1）。
func TestStatusTransitions(t *testing.T) {
	cases := []struct {
		from, to model.Status
	}{
		{model.StatusOpen, model.StatusInProgress},
		{model.StatusInProgress, model.StatusResolved},
		{model.StatusOpen, model.StatusResolved},   // 跨态前进
		{model.StatusResolved, model.StatusOpen},   // 回退（Jira Reopen 事实标准）
		{model.StatusResolved, model.StatusInProgress},
		{model.StatusOpen, model.StatusOpen},       // 自转：幂等 no-op
		{model.StatusInProgress, model.StatusInProgress},
		{model.StatusResolved, model.StatusResolved},
	}
	for _, c := range cases {
		repo := mem.New()
		svc := newService(repo)
		issue := mustCreate(t, svc)

		// 把 issue 推到起始状态（绕过状态机，仅测试目标流转）。
		if c.from != model.StatusOpen {
			ms := time.Now().UnixMilli()
			if _, err := repo.UpdateStatusIfCurrent(context.Background(), issue.ID,
				model.StatusOpen, c.from, ms, nil); err != nil {
				t.Fatal(err)
			}
		}

		got, err := svc.UpdateStatus(context.Background(), issue.ID, c.to)
		if err != nil {
			t.Errorf("transition %s -> %s: err = %v, want nil", c.from, c.to, err)
			continue
		}
		if got.Status != c.to {
			t.Errorf("transition %s -> %s: status = %s", c.from, c.to, got.Status)
		}
	}
}

