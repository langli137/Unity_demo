// TestUpdateStatusResolvedAt 进入 resolved 写 resolvedAt，离开清空，回退不残留。
func TestUpdateStatusResolvedAt(t *testing.T) {
	svc := newService(mem.New())
	issue := mustCreate(t, svc)

	// open -> in_progress：无 resolvedAt。
	mid, err := svc.UpdateStatus(context.Background(), issue.ID, model.StatusInProgress)
	if err != nil {
		t.Fatalf("to in_progress: %v", err)
	}
	if mid.ResolvedAt != nil {
		t.Error("resolvedAt should be nil before resolved")
	}

	// in_progress -> resolved：写入 resolvedAt。
	done, err := svc.UpdateStatus(context.Background(), issue.ID, model.StatusResolved)
	if err != nil {
		t.Fatalf("to resolved: %v", err)
	}
	if done.ResolvedAt == nil {
		t.Fatal("resolvedAt should be set when entering resolved")
	}
	first := *done.ResolvedAt

	// resolved 自转：保留首次解决时间（幂等）。
	self, err := svc.UpdateStatus(context.Background(), issue.ID, model.StatusResolved)
	if err != nil {
		t.Fatalf("self resolved: %v", err)
	}
	if self.ResolvedAt == nil || !self.ResolvedAt.Equal(first) {
		t.Error("self-transition resolved should keep original resolvedAt")
	}

	// resolved -> open（回退）：清空 resolvedAt。
	reopened, err := svc.UpdateStatus(context.Background(), issue.ID, model.StatusOpen)
	if err != nil {
		t.Fatalf("reopen: %v", err)
	}
	if reopened.ResolvedAt != nil {
		t.Error("resolvedAt should be cleared when leaving resolved")
	}
}

